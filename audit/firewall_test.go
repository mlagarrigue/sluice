// Rulesets as nft list ruleset and iptables-save print them, trimmed to
// what the question reads.

const nftOpen = `table inet filter {
	chain input {
		type filter hook input priority filter; policy drop;
		ct state established,related accept
		iifname "lo" accept
		tcp dport { 22, 5432 } accept
	}
}
`

const nftClosed = `table inet filter {
	chain input {
		type filter hook input priority filter; policy drop;
		ct state established,related accept
		ip saddr 10.0.0.0/8 tcp dport 5432 accept
		tcp dport 22 accept
	}
}
`

const nftPolicyAccept = `table ip filter {
	chain input {
		type filter hook input priority 0; policy accept;
		tcp dport 22 accept
	}
}
`

const iptablesOpen = `# Generated by iptables-save
*filter
:INPUT DROP [0:0]
:FORWARD ACCEPT [0:0]
-A INPUT -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
-A INPUT -p tcp -m multiport --dports 22,5000:6000 -j ACCEPT
COMMIT
`

const iptablesClosed = `*filter
:INPUT ACCEPT [0:0]
-A INPUT -s 10.0.0.0/8 -p tcp -m tcp --dport 5432 -j ACCEPT
-A INPUT -p tcp -m tcp --dport 5432 -j DROP
COMMIT
`

// Docker's -p 5432:5432: a DNAT in nat, which INPUT never sees.
const iptablesDocker = `*nat
:PREROUTING ACCEPT [0:0]
-A DOCKER ! -i docker0 -p tcp -m tcp --dport 15432 -j DNAT --to-destination 172.17.0.2:5432
COMMIT
*filter
:INPUT DROP [0:0]
COMMIT
`

const iptablesDockerLoopback = `*nat
-A DOCKER -d 127.0.0.1/32 ! -i docker0 -p tcp -m tcp --dport 5432 -j DNAT --to-destination 172.17.0.2:5432
COMMIT
*filter
:INPUT DROP [0:0]
-A INPUT -j DROP
COMMIT
`

func firewallFindings(t *testing.T, ruleset, settings string) []Finding {
	t.Helper()
	spec := Spec{Firewall: seedFile(t, "ruleset", ruleset)}
	if settings != "" {
		spec.PGSettings = seedFile(t, "settings.csv", settings)
	}
	target, err := Open(spec)
	if err != nil {
		t.Fatal(err)
	}
	findings, err := Run(Selection{Components: {"firewall"}}, nil, target)
	if err != nil {
		t.Fatal(err)
	}
	return findings
}

func TestThePostgresPortOpenToAnyAddressIsReported(t *testing.T) {
	for _, c := range []struct {
		name, ruleset, settings, want string
	}{
		{"nft, a set holding 5432", nftOpen, "", "line 6"},
		{"nft, a policy that accepts", nftPolicyAccept, "", "policy of chain input"},
		{"iptables-save, a multiport range", iptablesOpen, "", "line 6"},
		{"Docker's DNAT to 5432", iptablesDocker, "", "DNAT"},
		{"a port read in pg_settings", strings.ReplaceAll(nftOpen, "5432", "6543"), "name,setting,unit\nport,6543,\n", "line 6"},
		{"nft, a source on the rule", nftClosed, "", ""},
		{"iptables-save, restricted then dropped", iptablesClosed, "", ""},
		{"Docker published on 127.0.0.1", iptablesDockerLoopback, "", ""},
		{"a server listening on localhost", nftOpen, "name,setting,unit\nlisten_addresses,localhost,\n", ""},
	} {
		got := firewallFindings(t, c.ruleset, c.settings)
		switch {
		case c.want == "" && len(got) != 0:
			t.Errorf("%s: reported: %+v", c.name, got)
		case c.want == "":
		case len(got) != 1 || got[0].Rule != "firewall/postgres-exposed" || !strings.Contains(got[0].Current, c.want):
			t.Errorf("%s: %+v, want a finding naming %q", c.name, got, c.want)
		}
	}
}

