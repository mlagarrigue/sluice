//go:build ignore

// This program writes saslprep_tables.go from the tables of RFC 3454, the
// stringprep framework SASLprep (RFC 4013) is a profile of. The tables are
// frozen at Unicode 3.2 by the RFC itself, so the output only changes if the
// parsing does; it is generated rather than typed because typing a thousand
// ranges is how one of them ends up wrong.
//
//	go run saslprep_gen.go               # fetches the RFC from rfc-editor.org
//	go run saslprep_gen.go -rfc FILE     # reads a local copy
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

const rfcURL = "https://www.rfc-editor.org/rfc/rfc3454.txt"

// The tables this package needs, by RFC 4013 section, and the variable each
// becomes. libpq checks prohibited output and unassigned code points in one
// loop on the same string, so the two are one table here.
var outputs = []struct {
	name, doc string
	tables    []string
}{
	{"saslprepSpace", "is RFC 3454 table C.1.2, the non-ASCII spaces RFC 4013 §2.1 maps to U+0020.", []string{"C.1.2"}},
	{"saslprepNothing", "is RFC 3454 table B.1, the characters RFC 4013 §2.1 maps to nothing.", []string{"B.1"}},
	{"saslprepProhibited", "is the union of the prohibited output of RFC 4013 §2.3 (RFC 3454 tables C.1.2, C.2.1, C.2.2, C.3, C.4, C.5, C.6, C.7, C.8, C.9) and the unassigned code points of §2.5 (table A.1), which a stored string must not contain (RFC 3454 §7).", []string{"C.1.2", "C.2.1", "C.2.2", "C.3", "C.4", "C.5", "C.6", "C.7", "C.8", "C.9", "A.1"}},
	{"saslprepRandALCat", "is RFC 3454 table D.1, the characters with bidirectional property R or AL (RFC 4013 §2.4, RFC 3454 §6).", []string{"D.1"}},
	{"saslprepLCat", "is RFC 3454 table D.2, the characters with bidirectional property L (RFC 4013 §2.4, RFC 3454 §6).", []string{"D.2"}},
}

// An entry is one code point or a range, optionally followed by a semicolon
// and a description or mapping; page headers and footers match neither.
var entry = regexp.MustCompile(`^\s+([0-9A-F]{4,6})(?:-([0-9A-F]{4,6}))?(?:;|$)`)

func main() {
	rfc := flag.String("rfc", "", "local copy of RFC 3454 (default: fetch "+rfcURL+")")
	out := flag.String("o", "saslprep_tables.go", "output file")
	flag.Parse()

	text, err := read(*rfc)
	if err != nil {
		log.Fatal(err)
	}
	tables, err := parse(text)
	if err != nil {
		log.Fatal(err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by saslprep_gen.go from RFC 3454; DO NOT EDIT.\n\npackage postgres\n\nimport \"unicode\"\n")
	for _, o := range outputs {
		var rs [][2]rune
		for _, t := range o.tables {
			r, ok := tables[t]
			if !ok {
				log.Fatalf("table %s not found in the RFC", t)
			}
			rs = append(rs, r...)
		}
		writeTable(&b, o.name, o.doc, merge(rs))
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func read(path string) ([]byte, error) {
	if path != "" {
		return os.ReadFile(path)
	}
	resp, err := http.Get(rfcURL)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", rfcURL, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// parse returns every table between its "Start Table" and "End Table" marks.
func parse(text []byte) (map[string][][2]rune, error) {
	tables := map[string][][2]rune{}
	var current string
	sc := bufio.NewScanner(bytes.NewReader(text))
	for sc.Scan() {
		line := sc.Text()
		if name, ok := strings.CutPrefix(strings.TrimSpace(line), "----- Start Table "); ok {
			current = strings.TrimSuffix(name, " -----")
			continue
		}
		if strings.HasPrefix(strings.TrimSpace(line), "----- End Table ") {
			current = ""
			continue
		}
		if current == "" {
			continue
		}
		m := entry.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		lo, err := strconv.ParseUint(m[1], 16, 32)
		if err != nil {
			return nil, err
		}
		hi := lo
		if m[2] != "" {
			if hi, err = strconv.ParseUint(m[2], 16, 32); err != nil {
				return nil, err
			}
		}
		tables[current] = append(tables[current], [2]rune{rune(lo), rune(hi)})
	}
	return tables, sc.Err()
}

// merge sorts the ranges and joins those that overlap or touch.
func merge(rs [][2]rune) [][2]rune {
	slices.SortFunc(rs, func(a, b [2]rune) int { return int(a[0] - b[0]) })
	var out [][2]rune
	for _, r := range rs {
		if n := len(out); n > 0 && r[0] <= out[n-1][1]+1 {
			out[n-1][1] = max(out[n-1][1], r[1])
			continue
		}
		out = append(out, r)
	}
	return out
}

func writeTable(b *bytes.Buffer, name, doc string, rs [][2]rune) {
	fmt.Fprintf(b, "\n// %s %s\nvar %s = &unicode.RangeTable{\n", name, doc, name)
	var r16, r32 [][2]rune
	for _, r := range rs {
		switch {
		case r[1] <= 0xFFFF:
			r16 = append(r16, r)
		case r[0] > 0xFFFF:
			r32 = append(r32, r)
		default:
			r16 = append(r16, [2]rune{r[0], 0xFFFF})
			r32 = append(r32, [2]rune{0x10000, r[1]})
		}
	}
	latin := 0
	if len(r16) > 0 {
		b.WriteString("\tR16: []unicode.Range16{\n")
		for _, r := range r16 {
			fmt.Fprintf(b, "\t\t{Lo: 0x%04X, Hi: 0x%04X, Stride: 1},\n", r[0], r[1])
			if r[1] <= 0xFF {
				latin++
			}
		}
		b.WriteString("\t},\n")
	}
	if len(r32) > 0 {
		b.WriteString("\tR32: []unicode.Range32{\n")
		for _, r := range r32 {
			fmt.Fprintf(b, "\t\t{Lo: 0x%X, Hi: 0x%X, Stride: 1},\n", r[0], r[1])
		}
		b.WriteString("\t},\n")
	}
	if latin > 0 {
		fmt.Fprintf(b, "\tLatinOffset: %d,\n", latin)
	}
	b.WriteString("}\n")
}
